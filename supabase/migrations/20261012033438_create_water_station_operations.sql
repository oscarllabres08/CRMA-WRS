/*
# Create CRMA Water Refilling Station operations schema

1. New Tables
- `station_products` — products sold by the station, pricing, stock, and reorder thresholds.
- `station_customers` — customer directory and loyalty point balances.
- `station_sales` — completed sales with totals and payment information.
- `station_sale_items` — line items belonging to each sale.
- `station_expenses` — operating expenses tracked by the station.
- `station_settings` — shared station profile and operating preferences.

2. Security
- Row level security is enabled on every table.
- This is a single-tenant station workspace without a sign-in screen, so anon and authenticated roles receive CRUD access to the shared station data.

3. Notes
- IDs are generated by Postgres.
- Timestamps are maintained by Postgres.
- Sale items reference their sale and product records with safe foreign keys.
*/

CREATE TABLE IF NOT EXISTS station_products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  category text NOT NULL DEFAULT 'Refill',
  unit text NOT NULL DEFAULT 'container',
  price numeric(12,2) NOT NULL DEFAULT 0,
  stock numeric(12,2) NOT NULL DEFAULT 0,
  reorder_level numeric(12,2) NOT NULL DEFAULT 5,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS station_customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  phone text,
  address text,
  loyalty_points integer NOT NULL DEFAULT 0,
  total_spent numeric(12,2) NOT NULL DEFAULT 0,
  last_visit_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS station_sales (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid REFERENCES station_customers(id) ON DELETE SET NULL,
  subtotal numeric(12,2) NOT NULL DEFAULT 0,
  discount numeric(12,2) NOT NULL DEFAULT 0,
  total numeric(12,2) NOT NULL DEFAULT 0,
  payment_method text NOT NULL DEFAULT 'Cash',
  status text NOT NULL DEFAULT 'completed',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS station_sale_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sale_id uuid NOT NULL REFERENCES station_sales(id) ON DELETE CASCADE,
  product_id uuid REFERENCES station_products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  quantity numeric(12,2) NOT NULL DEFAULT 1,
  unit_price numeric(12,2) NOT NULL DEFAULT 0,
  line_total numeric(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS station_expenses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  category text NOT NULL DEFAULT 'Operations',
  amount numeric(12,2) NOT NULL DEFAULT 0,
  expense_date date NOT NULL DEFAULT CURRENT_DATE,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS station_settings (
  id integer PRIMARY KEY DEFAULT 1,
  station_name text NOT NULL DEFAULT 'CRMA Water Refilling Station',
  tagline text NOT NULL DEFAULT 'Pure water. Better life.',
  address text NOT NULL DEFAULT 'Pila St, Brgy. Camalig, Meycauayan, Bulacan',
  phone text NOT NULL DEFAULT '0956 158 9000',
  opening_hours text NOT NULL DEFAULT 'Mon-Fri 7:00 AM-6:00 PM · Sat 7:00 AM-12:00 PM',
  updated_at timestamptz NOT NULL DEFAULT now()
);

